#!/usr/bin/env python3
"""Write the catalog entry for the pinned HEAD, so its numbers cannot drift.

The catalog PR pins a full 40-character SHA. Hand-writing that file is how an entry
ends up quoting a version, a hook count or a tool count from three commits ago.
Run this at the commit you intend to publish:

    python3 tools/catalog_entry.py            # writes plugin-catalog/antemuse.yaml
    python3 tools/catalog_entry.py --check    # exit 1 if the fields drifted from HEAD

Nothing here pushes or opens a PR: the file exists in the repo so the PR is a copy.
The `source.ref` pin is written at release time — a commit cannot embed its own SHA — so
`--check` verifies the manifest-derived fields against HEAD and only requires that the
pinned SHA is a real commit in this repository.
"""
from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "plugin-catalog" / "antemuse.yaml"


def sh(*args: str) -> str:
    return subprocess.run(args, cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()


def head_sha() -> str:
    sha = sh("git", "rev-parse", "HEAD")
    if len(sha) != 40:
        raise SystemExit(f"not a full SHA: {sha!r}")
    return sha


def tree_is_clean() -> bool:
    return sh("git", "status", "--porcelain") == ""


def render() -> str:
    manifest = yaml.safe_load((ROOT / "plugin.yaml").read_text())
    sha = head_sha()
    entry = {
        "name": manifest["name"],
        "label": manifest["label"],
        "description": manifest["description"].strip(),
        "version": str(manifest["version"]),
        "author": manifest.get("author", ""),
        "homepage": manifest.get("homepage", ""),
        "category": "general",
        "tier": "community",
        "requires_hermes": manifest["requires_hermes"],
        "source": {
            "type": "github",
            "repo": "roosiq/antemuse-plugin",
            "ref": sha,
        },
        "provides": {
            "tools": list(manifest.get("provides_tools") or []),
            "hooks": list(manifest.get("provides_hooks") or []),
            "commands": ["/walk", "/daydream", "/doomscroll", "/dream", "/unstuck", "/return"],
        },
        "settings": sorted((manifest.get("config_schema") or {}).keys()),
        "disclosures": [
            "Network reads: doomscroll fetches public RSS/JSON feeds (8 s timeout, urllib, "
            "no credentials); results cached in the plugin data dir.",
            "Reads outside the data dir: daydream reads the operator's Hermes memory files; "
            "walks read local WordNet/FrameNet corpora via nltk.",
            "Writes: active state record, journal, residue, cursor and render caches under "
            "the plugin data dir; per-project artifacts under <repo>/.antemuse/.",
            "Child process: the full-screen takeover may spawn node to rasterise the live "
            "scene; it inherits no shell and falls back to cached frames when node is absent.",
            "Dev-only tools: scripts under tools/ make network calls and spawn browsers; "
            "they are never imported by plugin registration.",
            "Credentials: none requested, read, stored or refreshed.",
            "Telemetry and model usage: none. No analytics, no hidden LLM calls on the "
            "state path.",
            "Updates: the plugin never updates itself; updates arrive through this pinned "
            "SHA and 'hermes plugins update'.",
        ],
        "screenshots": [],
    }
    return "# Generated by tools/catalog_entry.py — do not hand-edit.\n" + yaml.safe_dump(
        entry, sort_keys=False, allow_unicode=True, width=100)


def _fields(text: str) -> dict:
    data = yaml.safe_load(text) or {}
    data.pop("source", None)
    return data


def _ref(text: str) -> str:
    return str(((yaml.safe_load(text) or {}).get("source") or {}).get("ref") or "")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists():
            print("missing plugin-catalog/antemuse.yaml", file=sys.stderr)
            return 1
        existing = OUT.read_text()
        if _fields(existing) != _fields(text):
            print("catalog entry's manifest-derived fields do not match HEAD: "
                  "re-run tools/catalog_entry.py at release time", file=sys.stderr)
            return 1
        ref = _ref(existing)
        if len(ref) != 40:
            print(f"catalog entry does not pin a full 40-char SHA (got {ref!r})", file=sys.stderr)
            return 1
        try:
            sh("git", "cat-file", "-e", f"{ref}^{{commit}}")
        except subprocess.CalledProcessError:
            print(f"pinned SHA {ref} is not a commit in this repository", file=sys.stderr)
            return 1
        note = "" if ref == head_sha() else " (an earlier validated commit; the pin is written at release)"
        print(f"catalog fields match HEAD · pin {ref[:12]}{note}")
        return 0
    if not tree_is_clean():
        print("warning: working tree is dirty; the pinned SHA will not match this tree",
              file=sys.stderr)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} for {head_sha()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
