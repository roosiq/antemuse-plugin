#!/usr/bin/env python3
"""Write the catalog entry for the pinned HEAD, so its numbers cannot drift.

The catalog PR pins a full 40-character SHA. Hand-writing that file is how an entry
ends up quoting a version, a hook count or a tool count from three commits ago.
Run this at the commit you intend to publish:

    python3 tools/catalog_entry.py            # writes plugin-catalog/antemuse.yaml
    python3 tools/catalog_entry.py --check    # exit 1 if the fields drifted from HEAD

Nothing here pushes or opens a PR: the file exists in the repo so the PR is a copy.
The `source.ref` pin is written at release time — a commit cannot embed its own SHA — so
`--check` verifies the manifest-derived fields against HEAD and only requires that the
pinned SHA is a real commit in this repository.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "plugin-catalog" / "antemuse.yaml"


def sh(*args: str) -> str:
    return subprocess.run(args, cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()


def head_sha() -> str:
    sha = sh("git", "rev-parse", "HEAD")
    if len(sha) != 40:
        raise SystemExit(f"not a full SHA: {sha!r}")
    return sha


def tree_is_clean() -> bool:
    return sh("git", "status", "--porcelain") == ""


def render(pin: str | None = None) -> str:
    """Render the entry in the schema hermes-agent's catalog loader accepts.

    The loader (hermes_cli/plugin_catalog.py) validates a flat mapping:
    name/repo/sha/description/maintainer/tier/category, plus optional docs_url,
    version, platforms, requires_hermes, title, known_issues, screenshots and a
    capabilities block. A nested ``source:`` block — the earlier shape of this
    file — is silently rejected, so it must not come back.
    """
    manifest = yaml.safe_load((ROOT / "plugin.yaml").read_text())
    sha = pin or head_sha()
    entry = {
        "name": manifest["name"],
        "title": manifest.get("label", "Antemuse"),
        "repo": "https://github.com/roosiq/antemuse-plugin",
        "sha": sha,
        "description": manifest["description"].strip(),
        "maintainer": "roosiq",
        "tier": "community",
        "category": "general",
        "docs_url": "https://github.com/roosiq/antemuse-plugin#readme",
        "version": str(manifest["version"]),
        "requires_hermes": manifest["requires_hermes"],
        # read from the manifest, so the entry cannot claim less (or more) than the plugin does
        "platforms": list(manifest.get("platforms") or ["linux", "macos"]),
        "capabilities": {
            "provides_tools": list(manifest.get("provides_tools") or []),
            "provides_hooks": list(manifest.get("provides_hooks") or []),
            "provides_middleware": [],
            "requires_env": [],
        },
        "known_issues": [
            "The picture is the desktop app's Antemuse pane only. Chat carries no visualization and "
            "a terminal gets the same text record; there is no terminal takeover since 0.10.30.",
            "Windows: the installer and runtime are pure Python and the suite passes on Linux; there "
            "is no Windows-specific path, so the pane is expected to work but is unverified there.",
            "The exploration library (spark, keep, collider, selection) is present but runtime-gated "
            "behind experimental.enabled and makes no quality claim.",
        ],
        "image": f"https://raw.githubusercontent.com/roosiq/antemuse-plugin/{sha}/docs/screenshots/banner.png",
        "screenshots": [
            f"https://raw.githubusercontent.com/roosiq/antemuse-plugin/{sha}/docs/screenshots/{n}"
            for n in ("pane-walk.png", "return-account.png", "blocked-tool.png")
        ],
    }
    text = yaml.safe_dump(entry, sort_keys=False, allow_unicode=True, width=100)
    # The catalog loader requires `version` to be a quoted string; safe_dump emits
    # 0.9.0 bare, which reads as a float in other parsers.
    text = re.sub(r"^version: (?![\"'])(.+)$", r'version: "\1"', text, flags=re.M)
    return "# Generated by tools/catalog_entry.py — do not hand-edit.\n" + text


def _fields(text: str) -> dict:
    data = yaml.safe_load(text) or {}
    data.pop("sha", None)
    # image/screenshots embed the pin, so normalise the SHA out of them before
    # comparing a file pinned to an earlier commit against a render at HEAD.
    def _norm(url: str) -> str:
        return re.sub(r"[0-9a-f]{40}", "{sha}", str(url))

    if "image" in data:
        data["image"] = _norm(data["image"])
    if isinstance(data.get("screenshots"), list):
        data["screenshots"] = [_norm(u) for u in data["screenshots"]]
    cap = data.get("capabilities")
    if isinstance(cap, dict):
        cap.pop("empty", None)
    return data


def _ref(text: str) -> str:
    return str((yaml.safe_load(text) or {}).get("sha") or "")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--pin", metavar="SHA",
                    help="pin an already-validated commit instead of HEAD")
    args = ap.parse_args()
    text = render(args.pin)
    if args.check:
        if not OUT.exists():
            print("missing plugin-catalog/antemuse.yaml", file=sys.stderr)
            return 1
        existing = OUT.read_text()
        if _fields(existing) != _fields(text):
            print("catalog entry's manifest-derived fields do not match HEAD: "
                  "re-run tools/catalog_entry.py at release time", file=sys.stderr)
            return 1
        ref = _ref(existing)
        if len(ref) != 40:
            print(f"catalog entry does not pin a full 40-char SHA (got {ref!r})", file=sys.stderr)
            return 1
        try:
            sh("git", "cat-file", "-e", f"{ref}^{{commit}}")
        except subprocess.CalledProcessError:
            print(f"pinned SHA {ref} is not a commit in this repository", file=sys.stderr)
            return 1
        note = "" if ref == head_sha() else " (an earlier validated commit; the pin is written at release)"
        print(f"catalog fields match HEAD · pin {ref[:12]}{note}")
        return 0
    if not tree_is_clean():
        print("warning: working tree is dirty; the pinned SHA will not match this tree",
              file=sys.stderr)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)} for {head_sha()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
