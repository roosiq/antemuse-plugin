#!/usr/bin/env python3
"""Generate the worked examples from the real engine.

Every block below is produced by running the plugin, not by describing it: the hop
lines, the account and the hit-rate line are printed by the code they document.
"""
from __future__ import annotations

import argparse
import os
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
OUT = ROOT / "docs" / "EXAMPLES.md"

# (title, command, kind)
SCENARIOS = (
    ("A familiar roadmap needs distance", "/walk", "walk"),
    ("Six hops later, the walk ends and says what arrived", "/walk", "walk-end"),
    ("You keep one concept and drop another", "cockpit · K / T", "verdict"),
    ("You want to look around yourself", "/explore", "explore"),
)


def _purge() -> None:
    for name in [n for n in sys.modules if n == "core" or n.startswith("core.")]:
        del sys.modules[name]


def _seed_walk(engine, walks, home: Path) -> None:
    walks.save({"name": "example", "title": "Example walk", "graph": "wordnet",
                "relations": walks.ALL_RELATIONS,
                "seed": {"mode": "word", "word": "design"}, "avoid_backtrack": True},
               cursor_path=home / "walk.json")
    engine.enter("walk", walk="example", session="example")


def run(kind: str) -> tuple[list[str], str, list[str]]:
    """One scenario: (journal lines, account, extra lines for the doc)."""
    home = tempfile.mkdtemp(prefix="example-")
    prior = os.environ.get("ANTEMUSE_STATES_HOME")
    os.environ["ANTEMUSE_STATES_HOME"] = home
    _purge()
    extra: list[str] = []
    try:
        from core import engine, history, walks

        if kind == "walk":
            _seed_walk(engine, walks, Path(home))
            for _ in range(6):
                engine.note_turn("example")
                engine.inject("example")
        elif kind == "walk-end":
            _seed_walk(engine, walks, Path(home))
            for _ in range(6):
                engine.note_turn("example")
                engine.inject("example")
            engine.complete_if_dosed()
        elif kind == "verdict":
            # The ledger is the only place taste is recorded; the report reads it back.
            history.notice("refactoring", move="keep", session="example")
            history.notice("zebra-tailed lizard", move="trash", session="example")
            tally = history.verdicts(30)
            total = tally["keep"] + tally["trash"]
            extra.append(f"hit rate: {tally['keep']} kept, {tally['trash']} trashed "
                         f"· {float(tally['rate']) * 100:.1f}%" if total else
                         "no verdicts recorded yet")
        else:
            engine.enter("explore", session="example")
            engine.note_pick(["design", "planning", "design"], session="example")
            engine.stop("example")

        data = engine._load()
        journal = [str(e.get("text") or "") for e in data.get("journal") or []
                   if e.get("who") == "state"]
        reports = [r for r in data.get("residue") or [] if r.get("kind") == "report"]
        return journal, str(reports[-1].get("text") if reports else ""), extra
    finally:
        _purge()
        if prior is None:
            os.environ.pop("ANTEMUSE_STATES_HOME", None)
        else:
            os.environ["ANTEMUSE_STATES_HOME"] = prior
        shutil.rmtree(home, ignore_errors=True)


def build() -> str:
    lines = ["# Worked examples", "", "Generated by `tools/examples.py`; do not edit by hand.",
             "", "Each block is output from the plugin, run against a throwaway home.", ""]
    for n, (title, command, kind) in enumerate(SCENARIOS, 1):
        journal, account, extra = run(kind)
        lines += [f"## {n}. {title}", "", f"Command: `{command}`", ""]

        if kind == "walk":
            lines += ["The walk records a path for the pane but does not inject it into the agent "
                      "turn. Each hop is the far rim of the concept's neighbourhood, not a "
                      "neighbour:", "", "```"]
            lines += journal[:6]
            lines += ["```", ""]
        elif kind == "walk-end":
            lines += ["The dose is six hops and each one is bought by a turn, so a walk cannot "
                      "finish itself while you are away. When the sixth hop is shown the state "
                      "ends and the next turn opens with an account:", "", "```text"]
            lines += [account or "(no account)"]
            lines += ["```", ""]
        elif kind == "verdict":
            lines += ["The cockpit names the concept under the reticle; `K` keeps it, `T` drops "
                      "it. A judgement is a sighting in the ledger whose move is the verdict, so "
                      "the report and the pane's tally count the same rows:", "", "```text"]
            lines += extra
            lines += ["```", ""]
        else:
            lines += ["The person chooses the concepts; the plugin only records the picks.",
                      ""]

        if kind == "walk" and account:
            lines += [f"The turn that follows the walk receives this account: `{account}`", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        text = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        expected = [f"## {n}. {title}" for n, (title, _command, _kind) in enumerate(SCENARIOS, 1)]
        if all(item in text for item in expected):
            print(f"ok: docs/EXAMPLES.md ({len(SCENARIOS)} examples)")
            return 0
        print("docs/EXAMPLES.md is missing or stale: run tools/examples.py")
        return 1
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
