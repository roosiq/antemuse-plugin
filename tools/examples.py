#!/usr/bin/env python3
"""Generate one worked example per agent state from the real engine."""
from __future__ import annotations

import argparse
import os
import shutil
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
OUT = ROOT / "docs" / "EXAMPLES.md"

SCENARIOS = (
    ("Distance while the work continues", "/walk", "walk"),
    ("Two memories make a possibility", "/daydream", "daydream"),
    ("Three useless things from the feed", "/doomscroll", "doomscroll"),
    ("The day recombines across projects", "/dream", "dream"),
    ("One direction breaks the stall", "/unstuck", "unstuck"),
)


def _purge() -> None:
    for name in [n for n in sys.modules if n == "core" or n.startswith("core.")]:
        del sys.modules[name]


def _seed_walk(engine, walks, home: Path) -> None:
    walks.save({"name": "example", "title": "Example walk", "graph": "wordnet",
                "relations": walks.ALL_RELATIONS,
                "seed": {"mode": "word", "word": "design"}, "avoid_backtrack": True},
               cursor_path=home / "walk.json")
    engine.enter("walk", walk="example", session="example")


def _seed_history(recall) -> None:
    """Give local readers enough private, throwaway context to demonstrate their contract."""
    recall.remember("The report is late because the dashboard is still hard to read.")
    recall.remember("The new layout prototype still has an unclear deployment boundary.")
    recall.remember("The deployment notes are scattered across the project.")


def run(key: str) -> tuple[list[str], str]:
    """Run one state against a throwaway home and return its material and account."""
    home = tempfile.mkdtemp(prefix="example-")
    prior = os.environ.get("ANTEMUSE_STATES_HOME")
    os.environ["ANTEMUSE_STATES_HOME"] = home
    _purge()
    try:
        from core import engine, recall, states, walks

        if key == "walk":
            _seed_walk(engine, walks, Path(home))
        else:
            _seed_history(recall)
            engine.enter(key, session="example")
        turns = int(states.STATES[key]["turns"])
        for _ in range(turns):
            engine.note_turn("example")
            engine.inject("example")
        engine.complete_if_dosed()
        data = engine._load()
        journal = [str(e.get("text") or "") for e in data.get("journal") or []
                   if e.get("who") == "state" and e.get("event") == key]
        reports = [r for r in data.get("residue") or [] if r.get("kind") == "report"
                   and r.get("state") == key]
        return journal, str(reports[-1].get("text") if reports else "")
    finally:
        _purge()
        if prior is None:
            os.environ.pop("ANTEMUSE_STATES_HOME", None)
        else:
            os.environ["ANTEMUSE_STATES_HOME"] = prior
        shutil.rmtree(home, ignore_errors=True)


def build() -> str:
    lines = ["# Worked examples", "", "Generated by `tools/examples.py`; do not edit by hand.",
             "", "Each block is output from the plugin, run against a throwaway home.", ""]
    for n, (title, command, key) in enumerate(SCENARIOS, 1):
        journal, account = run(key)
        lines += [f"## {n}. {title}", "", f"Command: `{command}`", ""]
        if key == "walk":
            lines += ["The walk records a path for the pane but does not inject it into the agent "
                      "turn:", "", "```"]
        else:
            lines += [f"The `{key}` material below is produced by its real provider:", "", "```text"]
        lines += journal or ["(the provider produced no material)"]
        lines += ["```", "", "Account:", "", "```text", account or "(no account)", "```", ""]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    if args.check:
        text = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        expected = [f"## {n}. {title}" for n, (title, _command, _key) in enumerate(SCENARIOS, 1)]
        if all(item in text for item in expected):
            print(f"ok: docs/EXAMPLES.md ({len(SCENARIOS)} state examples)")
            return 0
        print("docs/EXAMPLES.md is missing or stale: run tools/examples.py")
        return 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build(), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
